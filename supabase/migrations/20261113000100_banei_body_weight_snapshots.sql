-- Research-only Banei body-weight snapshots. No production model/table is changed.
create table if not exists public.banei_body_weight_snapshots (
  id bigint generated by default as identity primary key,
  race_id text not null,
  race_date date not null,
  venue text not null,
  race_number integer not null,
  horse_number integer not null,
  horse_name text not null,
  carried_weight numeric,
  body_weight numeric,
  body_weight_change numeric,
  captured_at timestamptz not null,
  scheduled_post_time timestamptz not null,
  minutes_to_post numeric not null,
  source text not null default 'NAR_OFFICIAL_DAILY_RACECARD',
  snapshot_hash text not null,
  constraint banei_body_weight_snapshots_hash_unique
    unique (race_id, horse_number, snapshot_hash),
  constraint banei_body_weight_snapshots_banei_only
    check (venue = '帯広')
);
create index if not exists idx_banei_weight_race_horse_time
  on public.banei_body_weight_snapshots (race_id, horse_number, captured_at desc);
create index if not exists idx_banei_weight_date_time
  on public.banei_body_weight_snapshots (race_date, captured_at desc);

alter table public.banei_body_weight_snapshots enable row level security;
drop policy if exists "banei body weight snapshots readable" on public.banei_body_weight_snapshots;
create policy "banei body weight snapshots readable"
  on public.banei_body_weight_snapshots for select to anon, authenticated using (true);

create or replace function public.invoke_nar_banei_weight_capture()
returns void language plpgsql security definer
set search_path = public, extensions, vault
as $$
declare capture_url text; capture_token text;
begin
  select decrypted_secret into capture_url
    from vault.decrypted_secrets where name = 'keiba_banei_weight_capture_url' limit 1;
  select decrypted_secret into capture_token
    from vault.decrypted_secrets where name = 'keiba_banei_weight_capture_token' limit 1;
  if capture_url is null or capture_token is null then
    raise notice 'Banei weight capture skipped: Vault secrets are not configured';
    return;
  end if;
  perform net.http_post(
    url := capture_url,
    headers := jsonb_build_object('Content-Type','application/json','Authorization','Bearer '||capture_token),
    body := jsonb_build_object('source','pg_cron','requested_at',now())
  );
end;
$$;

do $$
declare old_job record;
begin
  for old_job in select jobid from cron.job where jobname='keiba-lab-banei-weight-every-minute'
  loop perform cron.unschedule(old_job.jobid); end loop;
end $$;
select cron.schedule('keiba-lab-banei-weight-every-minute','* * * * *',
  'select public.invoke_nar_banei_weight_capture();');
