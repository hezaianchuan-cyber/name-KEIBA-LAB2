create table if not exists public.odds_archive_manifest (
  race_date date primary key,
  object_path text not null unique,
  row_count bigint not null check (row_count >= 0),
  uncompressed_bytes bigint not null check (uncompressed_bytes >= 0),
  compressed_bytes bigint not null check (compressed_bytes >= 0),
  sha256 text not null,
  verified_at timestamptz not null,
  created_at timestamptz not null default now()
);
alter table public.odds_archive_manifest enable row level security;

create table if not exists public.keiba_storage_health_log (
  id bigint generated by default as identity primary key,
  checked_at timestamptz not null default now(),
  database_bytes bigint not null,
  odds_table_bytes bigint not null,
  odds_rows bigint not null,
  archive_bucket_bytes bigint not null,
  quota_reference_bytes bigint not null,
  status text not null check (status in ('normal','warning','critical'))
);
create index if not exists idx_keiba_storage_health_checked_at
  on public.keiba_storage_health_log (checked_at desc);
alter table public.keiba_storage_health_log enable row level security;

create or replace function public.keiba_pending_archive_dates(p_before date, p_limit integer default 5)
returns table(race_date date)
language sql security definer set search_path = public
as $$
  select o.race_date
  from public.odds_snapshots o
  left join public.odds_archive_manifest m on m.race_date = o.race_date
  where o.race_date < p_before and m.race_date is null
  group by o.race_date
  order by o.race_date
  limit least(greatest(coalesce(p_limit, 5), 1), 31);
$$;

create or replace function public.keiba_storage_health()
returns jsonb
language sql security definer set search_path = public, storage
as $$
  with sizes as (
    select
      pg_database_size(current_database())::bigint as database_bytes,
      pg_total_relation_size('public.odds_snapshots')::bigint as odds_table_bytes,
      (select count(*) from public.odds_snapshots)::bigint as odds_rows,
      coalesce((
        select sum(coalesce(nullif(metadata->>'size','')::bigint, 0))
        from storage.objects where bucket_id = 'keiba-odds-archive'
      ), 0)::bigint as archive_bucket_bytes
  )
  select jsonb_build_object(
    'database_bytes', database_bytes,
    'database_mb', round(database_bytes / 1048576.0, 2),
    'odds_table_bytes', odds_table_bytes,
    'odds_rows', odds_rows,
    'archive_bucket_bytes', archive_bucket_bytes,
    'quota_reference_bytes', 524288000,
    'quota_reference', '500 MiB reference only; verify actual project plan quota',
    'warning_at_bytes', 367001600,
    'critical_at_bytes', 445644800,
    'status', case when database_bytes >= 445644800 then 'critical'
      when database_bytes >= 367001600 then 'warning' else 'normal' end
  )
  from sizes;
$$;

revoke all on function public.keiba_pending_archive_dates(date, integer) from public, anon, authenticated;
revoke all on function public.keiba_storage_health() from public, anon, authenticated;
grant execute on function public.keiba_pending_archive_dates(date, integer) to service_role;
grant execute on function public.keiba_storage_health() to service_role;

