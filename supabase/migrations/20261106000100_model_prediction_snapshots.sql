-- Immutable, timestamped model outputs used to join official pre-off odds.
create table if not exists public.model_prediction_snapshots (
  id bigint generated by default as identity primary key,
  race_id text not null,
  race_date date not null,
  captured_at timestamptz not null,
  scheduled_post_time timestamptz not null,
  model_version text not null,
  model_temperature double precision,
  predictions jsonb not null,
  candidate_combinations jsonb not null default '[]'::jsonb,
  model_g_version text,
  model_g_predictions jsonb not null default '[]'::jsonb,
  model_g_candidate_combinations jsonb not null default '[]'::jsonb,
  prediction_lock jsonb not null,
  created_at timestamptz not null default now(),
  constraint model_prediction_snapshots_race_capture_key unique (race_id, captured_at),
  constraint model_prediction_snapshots_preoff_check check (captured_at < scheduled_post_time),
  constraint model_prediction_snapshots_predictions_check check (jsonb_typeof(predictions) = 'array')
);

create index if not exists idx_model_prediction_snapshots_race_time
  on public.model_prediction_snapshots (race_id, captured_at desc);
create index if not exists idx_model_prediction_snapshots_date_time
  on public.model_prediction_snapshots (race_date, captured_at desc);

alter table public.model_prediction_snapshots enable row level security;

drop policy if exists "model prediction snapshots readable" on public.model_prediction_snapshots;
create policy "model prediction snapshots readable"
  on public.model_prediction_snapshots for select
  to anon, authenticated using (true);

grant select on public.model_prediction_snapshots to anon, authenticated;
revoke insert, update, delete on public.model_prediction_snapshots from anon, authenticated;
