-- KEIBA LAB: durable execution telemetry for the one-minute NAR odds capture.
create table if not exists public.odds_capture_runs (
  id bigint generated by default as identity primary key,
  started_at timestamptz not null,
  finished_at timestamptz not null default now(),
  status text not null check (status in ('success','error')),
  trigger_source text not null default 'pg_cron',
  elapsed_ms integer,
  race_rows integer not null default 0,
  positive_odds_rows integer not null default 0,
  races_in_preoff_window integer not null default 0,
  snapshots_inserted integer not null default 0,
  auto_ticket_plans_saved integer not null default 0,
  error_message text
);

create index if not exists idx_odds_capture_runs_finished
  on public.odds_capture_runs (finished_at desc);

alter table public.odds_capture_runs enable row level security;
drop policy if exists "odds capture runs readable" on public.odds_capture_runs;
create policy "odds capture runs readable"
  on public.odds_capture_runs for select
  to anon, authenticated using (true);

