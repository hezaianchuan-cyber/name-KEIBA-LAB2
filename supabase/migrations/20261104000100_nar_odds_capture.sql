-- KEIBA LAB: NAR pre-off odds snapshots
create extension if not exists pg_cron;
create extension if not exists pg_net with schema extensions;

create table if not exists public.odds_snapshots (
  id bigint generated by default as identity primary key,
  race_id text not null,
  race_date date not null,
  venue text,
  race_number integer,
  captured_at timestamptz not null default now(),
  odds_data jsonb not null,
  source text not null default 'NAR_OFFICIAL_DAILY_1MIN'
);

create index if not exists idx_odds_race_time
  on public.odds_snapshots (race_id, captured_at desc);
create index if not exists idx_odds_date_venue
  on public.odds_snapshots (race_date, venue);
create index if not exists idx_odds_venue_race
  on public.odds_snapshots (venue, race_number, race_date);

alter table public.odds_snapshots enable row level security;
drop policy if exists "odds snapshots readable" on public.odds_snapshots;
create policy "odds snapshots readable"
  on public.odds_snapshots for select
  to anon, authenticated using (true);

create or replace function public.invoke_nar_odds_capture()
returns void
language plpgsql
security definer
set search_path = public, extensions, vault
as $$
declare
  capture_url text;
  capture_token text;
begin
  select decrypted_secret into capture_url
  from vault.decrypted_secrets where name = 'keiba_capture_url' limit 1;
  select decrypted_secret into capture_token
  from vault.decrypted_secrets where name = 'keiba_capture_token' limit 1;
  if capture_url is null or capture_token is null then
    raise notice 'KEIBA LAB capture skipped: Vault secrets are not configured';
    return;
  end if;
  perform net.http_post(
    url := capture_url,
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'Authorization', 'Bearer ' || capture_token
    ),
    body := jsonb_build_object('source', 'pg_cron', 'requested_at', now())
  );
end;
$$;

do $$
declare old_job record;
begin
  for old_job in
    select jobid from cron.job
    where jobname = 'keiba-lab-nar-odds-every-minute'
  loop
    perform cron.unschedule(old_job.jobid);
  end loop;
end $$;

select cron.schedule(
  'keiba-lab-nar-odds-every-minute',
  '* * * * *',
  'select public.invoke_nar_odds_capture();'
);
